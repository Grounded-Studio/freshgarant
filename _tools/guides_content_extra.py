def apply(guides):
    by = {g["key"]: g for g in guides}
    for (key, lang), d in DESC.items():
        by[key][lang]["desc"] = d
    for (key, lang), (section, faqs) in EXTRA.items():
        a = by[key][lang]
        if section:
            i = a["body"].find("<h2>Tips")
            assert i > 0, (key, lang)
            a["body"] = a["body"][:i] + section.lstrip("\n") + "\n" + a["body"][i:]
        a["faq"] = a["faq"] + faqs
